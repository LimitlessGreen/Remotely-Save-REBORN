import { deepStrictEqual } from "assert";
import { AESCipherBlock, EMECipher } from "./";

interface TestVec {
  // direction
  isEncrypt: boolean;
  // AES key
  key: Uint8Array;
  // IV, in EME called tweak
  tweak: Uint8Array;
  // input data
  input: Uint8Array;
  // expected output data
  output: Uint8Array;
}

async function verifyTestVec(v: TestVec) {
  const bc = new AESCipherBlock(v.key);
  const eme = new EMECipher(bc);
  let output = new Uint8Array();
  let inputBack = new Uint8Array();

  if (v.isEncrypt) {
    output = (await eme.encrypt(v.tweak, v.input)) as any;
    inputBack = (await eme.decrypt(v.tweak, output)) as any;
  } else {
    output = (await eme.decrypt(v.tweak, v.input)) as any;
    inputBack = (await eme.encrypt(v.tweak, output)) as any;
  }

  deepStrictEqual(v.output, output);
  deepStrictEqual(v.input, inputBack);
}

